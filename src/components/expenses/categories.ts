/**
 * 経費のカテゴリ。
 *
 * ⚠️ **Web の `src/app/api/supabaseFunctions/supabaseDatabase/expenses/action.js` の
 *    `EXPENSE_CATEGORIES` と同じ綴りにすること。** サーバが配列に含まれるかで弾くので、
 *    1 文字でもずれると「カテゴリが不正です」で登録できなくなる。
 *    ⚠️ 2 リポジトリに同じ文字列を持っている（商品 ID と同じ罠）。**片方だけ直さない。**
 */
export const EXPENSE_CATEGORIES = [
  "仕入れ",
  "水道光熱費",
  "家賃",
  "管理費",
  "清掃費",
  "保険料",
  "修繕費",
  "消耗品費",
  "通信費",
  "広告宣伝費",
  "支払手数料",
  "その他",
] as const;

/**
 * 「その他」だけは**内容を自分で書ける**（2026-08-05）。
 *
 * ⚠️ **書いた内容は `note` に入る。カテゴリは "その他" のまま。**
 *    カテゴリを自由文字列にすると、サーバの検証（`EXPENSE_CATEGORIES.includes`）を
 *    緩めることになり、**集計とグラフの色が組織ごとにばらける。**
 *    一覧の行は `note` を出すので、画面上は「その他　町内会費」と読める。
 */
export const FREE_TEXT_CATEGORY: string = "その他";

export type ExpenseCategory = (typeof EXPENSE_CATEGORIES)[number];

/** 既定のカテゴリ。⚠️ 在庫の仕入れがいちばん多いので先頭に置いてある */
export const DEFAULT_CATEGORY: string = EXPENSE_CATEGORIES[0];

/**
 * カテゴリごとの色。円グラフの扇と、その横の内訳の点に使う。
 *
 * ⚠️ **12 色を色相だけで配らない。** 2026-08-06 まで全部を中間の明るさで
 *    揃えていたため、**家賃(#8B5CF6) と 管理費(#A855F7)**、
 *    **水道光熱費(#F59E0B) と 保険料(#F97316)**、**清掃費(#14B8A6) と
 *    消耗品費(#10B981)** が並ぶと**同じ色にしか見えなかった。**
 *    色相環は 12 等分すると隣どうしが 30 度しか離れず、扇として並べたときに
 *    区別が付かない。
 *
 * **したがって「6 つの色系統 × 濃淡 2 段」で組んである。**
 * 同じ系統の 2 つは必ず**明度で大きく離す**こと。
 *
 * | 系統 | 濃 | 淡 |
 * |---|---|---|
 * | シアン | 仕入れ | 通信費 |
 * | 黄 | 保険料 | 水道光熱費 |
 * | 紫 | 家賃 | 広告宣伝費 |
 * | 赤桃 | 修繕費 | 管理費 |
 * | 緑 | 清掃費 | 消耗品費 |
 * | グレー | 支払手数料 | その他 |
 *
 * ⚠️ **カテゴリを足すときは系統を 1 つ増やすか、空いている濃淡へ入れること。**
 *    既存の色の近くに足すと、また見分けが付かなくなる。
 * ⚠️ 未知のカテゴリ（あとから増やした・古いデータ）も来うるので、必ず既定色に落とすこと。
 * ⚠️ **Web の `src/functions/expenseCategories.js` と同じ値にすること。**
 *    片方だけ直すと、同じ経費が Web とアプリで違う色になる。
 */
const CATEGORY_COLOR: Record<string, string> = {
  仕入れ: "#0E7490",
  水道光熱費: "#FBBF24",
  家賃: "#6D28D9",
  管理費: "#F472B6",
  清掃費: "#4D7C0F",
  保険料: "#B45309",
  修繕費: "#DC2626",
  消耗品費: "#34D399",
  通信費: "#38BDF8",
  広告宣伝費: "#A78BFA",
  支払手数料: "#475569",
  その他: "#94A3B8",
};

export function categoryColor(category: string): string {
  return CATEGORY_COLOR[category] ?? CATEGORY_COLOR["その他"];
}
